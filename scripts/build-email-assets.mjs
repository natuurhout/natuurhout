// Builds the small images the quote e-mails embed (logo + mascot) and writes
// them as base64 into src/lib/email-assets.ts. They travel inside the mail as
// inline attachments (cid:), so they show without the "download pictures"
// prompt Outlook puts on remote images, and keep working on any domain.
// Run after changing the logo or mascot: node scripts/build-email-assets.mjs
import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";

const root = process.cwd();
const sources = {
  logo: { file: "public/wp-content/uploads/2016/01/logo-natuurhout-new-1.png", width: 400 }, // shown at 200 px
  mascot: { file: "public/mascotte-natuurhout.webp", width: 128 }, // shown at 64 px
};

// The mascot photo sits on an off-white backdrop that shows as a grey square
// on the white mail header: crop to the figure and push near-white to white.
async function whiten(input) {
  const { data, info } = await sharp(input).trim({ threshold: 20 }).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  for (let i = 0; i < data.length; i += 4) {
    if (data[i] > 225 && data[i + 1] > 225 && data[i + 2] > 225) data[i] = data[i + 1] = data[i + 2] = 255;
  }
  return sharp(data, { raw: info }).png().toBuffer();
}

const out = {};
for (const [name, { file, width }] of Object.entries(sources)) {
  const input = name === "mascot" ? await whiten(path.join(root, file)) : path.join(root, file);
  const buffer = await sharp(input)
    .resize({ width, height: name === "mascot" ? width : undefined, fit: "contain", background: "#ffffff" })
    .flatten({ background: "#ffffff" }) // the mail header is white; Outlook mishandles alpha
    .png({ compressionLevel: 9, palette: true })
    .toBuffer();
  const { height } = await sharp(buffer).metadata();
  out[name] = { base64: buffer.toString("base64"), width: width / 2, height: Math.round(height / 2), bytes: buffer.length };
  console.log(`${name}: ${buffer.length} bytes, shown at ${width / 2}×${Math.round(height / 2)}`);
}

const body = `// Generated by scripts/build-email-assets.mjs — do not edit by hand.
// PNGs at 2× the size they are shown at in the quote e-mails.

export type EmailImage = { cid: string; filename: string; base64: string; width: number; height: number };

${Object.entries(out)
  .map(
    ([name, a]) => `export const ${name}Image: EmailImage = {
  cid: "natuurhout-${name}",
  filename: "natuurhout-${name}.png",
  width: ${a.width},
  height: ${a.height},
  base64: "${a.base64}",
};`,
  )
  .join("\n\n")}
`;
fs.writeFileSync(path.join(root, "src/lib/email-assets.ts"), body);
console.log("wrote src/lib/email-assets.ts");
